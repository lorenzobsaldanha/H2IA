    # Apague a linha abaixo e escreva suas regras com if, elif e else.
    if (mass < 100):
      return 'mandarim'
    elif (color_score >= 0.70 and color_score <= 0.73) and ((height - width) > 1):
      return 'lemon'
    elif ((height - width) < 0.5) and (color_score >= 0.72 and color_score <= 0.82):
      return 'orange'
    elif (not (color_score >= 0.71 and color_score <= 0.82)):
      return 'apple'

